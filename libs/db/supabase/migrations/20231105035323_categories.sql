CREATE OR REPLACE FUNCTION public.insight_category (user_id bigint, category_path ltree, at daterange)
    RETURNS TABLE (
        type event_type,
        attendance event_attendance,
        name text,
        value text,
        count integer,
        minutes integer)
    LANGUAGE plpgsql
    AS $function$
BEGIN
    RETURN QUERY
    SELECT
        insight.type,
        insight.attendance,
        insight.name,
        insight.value,
        SUM(insight.count)::integer AS count,
        SUM(insight.minutes)::integer AS minutes
    FROM
        insight
    WHERE
        insight.user_id = insight_category.user_id
        AND insight_category.category_path @> insight.category_path
        AND insight_category.at @> insight.day
    GROUP BY
        insight.type,
        insight.attendance,
        insight.name,
        insight.value;
END;
$function$;

CREATE OR REPLACE FUNCTION public.calc_event_type (at tstzrange, availability event_availability, response event_response, has_invitees boolean)
    RETURNS event_type
    LANGUAGE plpgsql
    AS $function$
BEGIN
    RETURN CASE WHEN calc_all_day (at) THEN
        'note'::event_type
    WHEN has_invitees
        AND (availability = 'busy'
            OR response = 'declined') THEN
        'meeting'::event_type
    ELSE
        'task'::event_type
    END;
END;
$function$;

