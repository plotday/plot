    text2ltree (min(ltree2text (insight.category_path))) AS category_path,
    insight.type,
    sum(insight.count) FILTER (WHERE (insight.attendance = 'attend'::event_attendance)) AS count,
sum(insight.minutes) FILTER (WHERE (insight.attendance = 'attend'::event_attendance)) AS minutes,
sum(insight.count) FILTER (WHERE (insight.attendance IS NULL)) AS pending_count,
sum(insight.minutes) FILTER (WHERE (insight.attendance IS NULL)) AS pending_minutes
FROM
    insight
WHERE (insight.name = 'Total'::text)
GROUP BY
    insight.user_id,
    (date_trunc('week'::text, (insight.day)::timestamp with time zone)),
    insight.category_id,
    insight.type;

CREATE OR REPLACE VIEW "public"."balance" AS
SELECT
    g.user_id,
    g.week,
    g.category_id,
    g.category_path,
    g.type,
    sum((g.weekly_minutes - COALESCE(i.minutes, (0)::bigint))) OVER w AS minutes,
    sum(i.pending_minutes) OVER w AS pending_minutes
FROM (goal_weekly g
    LEFT JOIN category_total_weekly i ON (((g.user_id = i.user_id)
                AND (g.week = i.week)
                AND (g.category_path <@ i.category_path)
                AND goal_type_equal (g.type, i.type))))
WINDOW w AS (PARTITION BY g.user_id, g.category_id, g.type ORDER BY g.week RANGE BETWEEN '21 days'::interval PRECEDING AND CURRENT ROW);

